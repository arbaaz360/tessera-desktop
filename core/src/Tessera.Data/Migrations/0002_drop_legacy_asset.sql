-- The bridge back to Immich's identifiers is no longer needed.
--
-- legacy_asset mapped Immich asset uuids to content, because Foundation and
-- FaceSearch keyed 1.9M vectors and 1.4M faces on those uuids and re-embedding
-- to change the key would have been days of GPU. It was written to be dropped
-- the day both carried the hash instead - see db/02-legacy.sql in the history.
--
-- That day is 2026-09-11. Both systems now carry the SHA-256 on every row
-- (backfilled from the map ops/export-legacy-ids.sh wrote), answer in it, and
-- Tessera resolves it directly against content.sha256. The last thing that
-- read this table - the covers migration phase - ran before this did.
--
-- Nothing on this machine speaks an Immich asset id from here on.
DROP TABLE IF EXISTS legacy_asset;
